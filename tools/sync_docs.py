#!/usr/bin/env python3
"""Generate the manifest, the README status block and paper map, and the CORRESPONDENCE table.

`ledger/manifest.yaml` is generated from `tools/nodes.py` and the frozen files (whose blocks it
pins by SHA-256).  The README and CORRESPONDENCE blocks between `<!-- X-BEGIN -->` and
`<!-- X-END -->` are generated from the manifest.  With `--write` the files are rewritten; without
it they are compared and the exit code is nonzero on any difference.
"""
import textwrap
import pathlib
import sys

import yaml

from common import ROOT, frozen_block, sha256
from nodes import CORRECTED_PAPER_SHA256, GUARDS, NODES, NOT_FORMALIZED, PAPER_SHA256

PAPER = "paper/rw-spheres.tex"
CORRECTED_PAPER = "paper/rw-spheres-corrected.tex"


def manifest_text() -> str:
    nodes = []
    for (nid, paper, label, lines, title, file, export, form, prov, note) in NODES:
        path = ROOT / "SpherePackings/Frozen" / f"{file}.lean"
        nodes.append({
            "id": nid, "paper": paper, "title": title,
            "source": f"rw-spheres.tex:{lines} (label {label})",
            "file": f"SpherePackings/Frozen/{file}.lean",
            "export": f"SpherePackings.Frozen.{export}",
            "form": form, "provenance": prov, "state": "PARTIAL" if form == "weakened" else "PROVED",
            "frozen_sha256": sha256(frozen_block(path)),
            "note": note,
        })
    data = {
        "version": 1,
        "source_pin": {"file": PAPER, "sha256": PAPER_SHA256},
        "corrected_source_pin": {"file": CORRECTED_PAPER, "sha256": CORRECTED_PAPER_SHA256},
        "nodes": nodes,
        "not_formalized": [{"paper": p, "label": lab, "source": f"rw-spheres.tex:{lines}", "reason": r}
                           for (p, lab, lines, r) in NOT_FORMALIZED],
        "guards": [{"export": e, "file": f, "role": r} for (e, f, r) in GUARDS],
    }
    head = ("# Frozen-statement manifest of Random-Walk-On-Sphere-Packings (generated by\n"
            "# tools/sync_docs.py from tools/nodes.py).  The bytes between the FROZEN-STATEMENT\n"
            "# markers of each node's file are pinned by `frozen_sha256`.  `form` says whether the\n"
            "# statement is the printed one, a corrected one, a reformulation or a weakened one;\n"
            "# CORRESPONDENCE.md explains each.  `provenance` names who proved it.\n")
    return head + yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=100)


def lean_link(file: str, export: str) -> str:
    text = (ROOT / file).read_text(encoding="utf-8").split("\n")
    line = next(i for i, l in enumerate(text, 1) if l.startswith(f"theorem {export}"))
    return f"[{export}]({file}#L{line})"


def paper_link(paper: str, source: str) -> str:
    start = source.split(":")[1].split("-")[0].split(" ")[0]
    return f"[{paper}](paper/rw-spheres.tex#L{start})"


def status_block(data: dict) -> str:
    nodes = data["nodes"]
    full = [n for n in nodes if n["state"] == "PROVED"]
    partial = [n for n in nodes if n["state"] == "PARTIAL"]
    phrase = {"as printed": "as printed",
              "corrected": "as in the corrected paper, where the printed statement is changed, "
                           "documented below"}
    forms = {}
    for n in full:
        forms[n["form"]] = forms.get(n["form"], 0) + 1
    order = ["as printed", "corrected"] + sorted(k for k in forms if k not in ("as printed", "corrected"))
    detail = ", ".join(f"{forms[k]} {phrase.get(k, k)}" for k in order if k in forms)
    names = []
    for n in partial:
        if n["paper"] not in names:
            names.append(n["paper"])
    listed = [f"{x} (both statements)" if sum(n["paper"] == x for n in partial) > 1 else x for x in names]
    which = ", ".join(listed[:-1]) + (" and " if len(listed) > 1 else "") + listed[-1] if listed else ""
    np = len(partial)
    partial_text = (f"  **{np} {'is' if np == 1 else 'are'} `PARTIAL`**: proved under a hypothesis stronger than "
                    f"the corrected paper's ({which}; see \"Open\" below)." if np else
                    "  None is `PARTIAL`.")
    text = (f"Status: **{len(nodes)} registered statements.  {len(full)} are `PROVED`** ({detail})."
            f"{partial_text}  Every axiom closure is exactly Lean's three standard axioms `propext`, "
            "`Classical.choice` and `Quot.sound`: no `sorry`, and no axiom added by this development.  "
            f"{len(data['not_formalized'])} labelled items have no registered statement (see below).  These "
            "counts are generated from `ledger/manifest.yaml` by `python3 tools/sync_docs.py`.")
    return textwrap.fill(text, width=100, break_long_words=False, break_on_hyphens=False) + "\n"


def paper_map(data: dict) -> str:
    rows = ["| Paper result | Lean statement | Form | Proved by | Note |", "|---|---|---|---|---|"]
    for n in data["nodes"]:
        label = n["source"].split("label ")[1].rstrip(")")
        rows.append(f"| {paper_link(n['paper'], n['source'])}: {n['title']}<br>`{label}` | "
                    f"{lean_link(n['file'], n['export'])} | {n['form']} | {n['provenance']} | {n['note']} |")
    rows += ["", "Labelled items with no registered statement:", "",
             "| Paper item | Reason |", "|---|---|"]
    for x in data["not_formalized"]:
        rows.append(f"| {paper_link(x['paper'], x['source'])} | {x['reason']} |")
    rows += ["", "Supporting statements that establish properties of the formal model:", "",
             "| Role | Lean statement |", "|---|---|"]
    for g in data["guards"]:
        short = g["export"]
        rows.append(f"| {g['role']} | [{short}]({g['file']}) |")
    return "\n".join(rows) + "\n"


def replace_block(text: str, tag: str, body: str) -> str:
    begin, end = f"<!-- {tag}-BEGIN (generated by tools/sync_docs.py) -->", f"<!-- {tag}-END -->"
    if begin not in text or end not in text:
        raise SystemExit(f"missing {tag} markers")
    pre, rest = text.split(begin, 1)
    post = rest.split(end, 1)[1]
    return f"{pre}{begin}\n\n{body}\n{end}{post}"


def main() -> int:
    write = "--write" in sys.argv
    outputs = {}
    mtext = manifest_text()
    outputs[ROOT / "ledger/manifest.yaml"] = mtext
    data = yaml.safe_load(mtext)
    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    readme = replace_block(readme, "STATUS", status_block(data))
    readme = replace_block(readme, "PAPER-MAP", paper_map(data))
    outputs[ROOT / "README.md"] = readme
    corr = (ROOT / "CORRESPONDENCE.md").read_text(encoding="utf-8")
    corr = replace_block(corr, "NODE-TABLE", paper_map(data))
    outputs[ROOT / "CORRESPONDENCE.md"] = corr
    bad = 0
    for path, text in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current != text:
            if write:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
                print(f"wrote {path.relative_to(ROOT)}")
            else:
                print(f"sync_docs: {path.relative_to(ROOT)} is out of date (run with --write)")
                bad = 1
    if not bad:
        print("sync_docs: OK")
    return bad


if __name__ == "__main__":
    sys.exit(main())
