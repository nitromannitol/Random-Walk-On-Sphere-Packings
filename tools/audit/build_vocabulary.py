#!/usr/bin/env python3
"""Assemble the Mathlib-only vocabulary modules of the comparator challenges.

Input: the JSON lines written by `tools/audit/DumpVocabulary.lean` (every declaration of each
project module involved in the challenge statements, with its source range and whether a
statement needs it).  Output: for each involved module `M`, the file
`SpherePackingsAudit/Vocabulary/<M>.lean`, a copy of `M` with the unneeded declarations removed
and everything else (namespaces, `open`, `variable`, comments) kept verbatim.  It imports the
Mathlib modules imported by `M` and by the project modules below it, and the vocabulary copies
of the involved project modules below it.  The module structure is kept so that the copies
elaborate to the same terms as the repository (Lean shares auxiliary proofs only within a
module).

Usage: build_vocabulary.py <dump.jsonl> [--check]
With `--check`, the files are compared with the existing ones instead of written; the exit code
is nonzero on any difference.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "SpherePackingsAudit" / "Vocabulary"
HEADER_PREFIXES = ("-- Copied from Leonardo Bonanno", "-- https://github.com/leobon12",
                   "-- (file `BouRabeeGwynne/")
CREDIT = ("-- Copied from Leonardo Bonanno's (leobon12) formalization of this paper,\n"
          "-- https://github.com/leobon12/lean-formalizations/tree/main/results/bou-rabee-gwynne\n")


def module_path(module: str) -> pathlib.Path:
    return ROOT / (module.replace(".", "/") + ".lean")


def imports(module: str) -> list[str]:
    out = []
    for line in module_path(module).read_text().splitlines():
        m = re.match(r"^import\s+(\S+)\s*$", line)
        if m:
            out.append(m.group(1))
    return out


def is_project(m: str) -> bool:
    return m.startswith("BouRabeeGwynne") or m.startswith("SpherePackings")


def ancestors(module: str, cache: dict) -> set[str]:
    if module in cache:
        return cache[module]
    result: set[str] = set()
    for m in imports(module):
        if is_project(m):
            result.add(m)
            result |= ancestors(m, cache)
    cache[module] = result
    return result


def vocabulary_name(module: str) -> str:
    return "SpherePackingsAudit.Vocabulary." + module


def render(module: str, rows: list[dict], involved: set[str], cache: dict) -> str:
    below = ancestors(module, cache)
    mathlib = sorted({i for m in below | {module} for i in imports(m) if i.startswith("Mathlib")})
    vocab = sorted(vocabulary_name(m) for m in below & involved)
    lines = module_path(module).read_text().splitlines()
    keep = [False] * (len(lines) + 2)
    drop = [False] * (len(lines) + 2)
    for r in rows:
        if r["module"] == module and r["needed"]:
            for i in range(r["start"], r["stop"] + 1):
                keep[i] = True
    for r in rows:
        if r["module"] == module and not r["needed"]:
            for i in range(r["start"], r["stop"] + 1):
                drop[i] = True
            # A command modifier such as `open Foo in` on the preceding line belongs to it.
            j = r["start"] - 1
            while j >= 1 and re.match(r"^(open|set_option)\b.*\bin\s*$", lines[j - 1]):
                drop[j] = True
                j -= 1
    # A repository module's leading comment lines (its attribution header) are moved, whole, above
    # the vocabulary note; a copied module's header is replaced by `CREDIT`.
    copied = module.startswith("BouRabeeGwynne.")
    lead = 0
    while not copied and lead < len(lines) and lines[lead].startswith("-- "):
        lead += 1
    body = []
    for i, line in enumerate(lines, start=1):
        if i <= lead or (drop[i] and not keep[i]) or re.match(r"^import\s", line) \
                or (copied and line.startswith(HEADER_PREFIXES)):
            continue
        body.append(line)
    text = re.sub(r"\n{3,}", "\n\n", "\n".join(body)).strip("\n")
    source = module.replace(".", "/") + ".lean"
    head = "\n".join(f"import {i}" for i in mathlib + vocab)
    credit = CREDIT if copied else "".join(line + "\n" for line in lines[:lead])
    return (f"{head}\n\n{credit}-- VOCABULARY: the declarations of `{source}` needed to state the challenges,\n"
            f"-- copied verbatim; generated by `tools/audit/build_vocabulary.py`.\n\n{text}\n")


def main() -> None:
    rows = [json.loads(line) for line in pathlib.Path(sys.argv[1]).read_text().splitlines()]
    check = "--check" in sys.argv[2:]
    involved = {r["module"] for r in rows}
    cache: dict = {}
    bad = 0
    for m in sorted(involved):
        path = OUT / (m.replace(".", "/") + ".lean")
        text = render(m, rows, involved, cache)
        if check:
            if not path.exists() or path.read_text() != text:
                print(f"MISMATCH {path.relative_to(ROOT)}")
                bad += 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(path.relative_to(ROOT))
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
