#!/usr/bin/env python3
"""Generate CERTIFICATE.md: toolchain, dependency pins, and each node's axiom closure and hash.

The axiom closures are computed afresh by `#print axioms`; the file is written only if every
closure is within `propext`, `Classical.choice`, `Quot.sound`.  With `--check`, the generated text
is compared with the committed file.
"""
import json
import sys

import yaml

from common import ROOT, STANDARD_AXIOMS, parse_axioms, run_lean_file


def main() -> int:
    man = yaml.safe_load((ROOT / "ledger/manifest.yaml").read_text(encoding="utf-8"))
    entries = [(n["export"], n["file"]) for n in man["nodes"]] + \
        [(g["export"], g["file"]) for g in man["guards"]]
    mods = sorted({f[:-5].replace("/", ".") for _, f in entries})
    src = "".join(f"import {m}\n" for m in mods) + "".join(f"#print axioms {e}\n" for e, _ in entries)
    result = run_lean_file(src)
    found = parse_axioms(result.stdout)
    if result.returncode or any(e not in found or not found[e] <= STANDARD_AXIOMS for e, _ in entries):
        print("certificate: FAIL: Lean error or non-standard axiom; not written")
        return 1
    toolchain = (ROOT / "lean-toolchain").read_text().strip()
    lake = json.loads((ROOT / "lake-manifest.json").read_text())
    pins = {p["name"]: p["rev"] for p in lake["packages"]}
    lines = ["# Certificate", "",
             "Generated by `python3 tools/certificate.py` after a successful axiom audit.", "",
             f"- Lean toolchain: `{toolchain}`",
             f"- Mathlib: `{pins['mathlib']}`",
             f"- Paper source `{man['source_pin']['file']}`: SHA-256 `{man['source_pin']['sha256']}`", "",
             "Every declaration below depends on exactly the axioms listed, all among Lean's three",
             "standard axioms `propext`, `Classical.choice`, `Quot.sound`.", "",
             "| Node | Paper | Declaration | Axioms | Frozen statement SHA-256 |",
             "|---|---|---|---|---|"]
    for n in man["nodes"]:
        ax = ", ".join(sorted(found[n["export"]]))
        lines.append(f"| `{n['id']}` | {n['paper']} | `{n['export']}` | {ax} | `{n['frozen_sha256']}` |")
    lines += ["", "Guards:", "", "| Declaration | Axioms |", "|---|---|"]
    for g in man["guards"]:
        lines.append(f"| `{g['export']}` | {', '.join(sorted(found[g['export']]))} |")
    text = "\n".join(lines) + "\n"
    path = ROOT / "CERTIFICATE.md"
    if "--check" in sys.argv:
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            print("certificate: CERTIFICATE.md is out of date")
            return 1
        print("certificate: OK")
        return 0
    path.write_text(text, encoding="utf-8")
    print("certificate: wrote CERTIFICATE.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
